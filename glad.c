__attribute__((pure)) static int glad_gl_has_extension(const char *exts, char **exts_i, const char *ext) {
    if(exts_i) {
        unsigned int index;
        for(index = 0; exts_i[index]; index++) {
            const char *e = exts_i[index];
            if(StringsEqual(e, ext)) return 1;
        }
    } else {
        const char *extensions;
        const char *loc;
        const char *terminator;
        extensions = exts;
        if(extensions == NULL || ext == NULL) return 0;

        while(1) {
            loc = StringFindSubstring(extensions, ext);
            if(loc == NULL) return 0;

            terminator = loc + GetStringLength(ext);
            if((loc == extensions || *(loc - 1) == ' ') && (*terminator == ' ' || *terminator == '\0')) return 1;

            extensions = terminator;
        }
    }
    
    return 0;
}

